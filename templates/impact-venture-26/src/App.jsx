      // Close mobile menu on resize / on nav click outside
      function initGlobalHandlers() {
          // Close menu on wider screens
          window.addEventListener("resize", () => {
              const menu = document.getElementById("mobileMenu");
              if (!menu) return;
              if (window.innerWidth >= 1024 && menu.classList.contains("open")) {
                  menu.classList.remove("open");
                  const icon = document.getElementById("menuIcon");
                  if (icon) {
                      icon.setAttribute("data-lucide", "menu");
                      initIcons();
                  }
                  const btn = document.getElementById("mobileMenuBtn");
                  if (btn) btn.setAttribute("aria-expanded", "false");
              }
          });

          // Close menu when clicking outside
          document.addEventListener("click", (e) => {
              const menu = document.getElementById("mobileMenu");
              const btn = document.getElementById("mobileMenuBtn");
              if (!menu || !btn) return;
              const content = document.querySelector(".mobile-menu-content");
              const isOpen = menu.classList.contains("open");
              if (!isOpen) return;

              const target = e.target;
              if (btn.contains(target) || (content && content.contains(target))) return;

              menu.classList.remove("open");
              const icon = document.getElementById("menuIcon");
              if (icon) {
                  icon.setAttribute("data-lucide", "menu");
                  initIcons();
              }
              btn.setAttribute("aria-expanded", "false");
          }, true);

          // Keyboard support for mobile menu button
          const btn = document.getElementById("mobileMenuBtn");
          if (btn) {
              btn.setAttribute("aria-label", "Toggle menu");
              btn.setAttribute("aria-expanded", "false");
          }
      }


      // Apply translations
      function applyTranslations(lang) {
          const dict = translations[lang] || translations.en;

          document.querySelectorAll("[data-i18n]").forEach((el) => {
              const key = el.getAttribute("data-i18n");
              const val = dict[key];
              if (!val) return;

              // If text includes HTML (e.g., footer desc), use innerHTML
              if (typeof val === "string" && (val.includes("<br") || val.includes("&copy;") || val.includes("©"))) {
                  el.innerHTML = val;
              } else {
                  el.textContent = val;
              }
          });

          // Body language class for font switching
          document.body.classList.toggle("lang-zh", lang === "zh");

          // Toggle labels
          const next = lang === "en" ? "中文" : "EN";
          const langText = document.getElementById("langText");
          const langTextMobile = document.getElementById("langTextMobile");
          if (langText) langText.textContent = next;
          if (langTextMobile) langTextMobile.textContent = next;

          // Document language attribute
          document.documentElement.setAttribute("lang", lang === "zh" ? "zh-Hant" : "en");
      }

      // Toggle language
      function toggleLanguage() {
          currentLang = currentLang === "en" ? "zh" : "en";
          applyTranslations(currentLang);
      }

      // Mobile menu
      function toggleMobileMenu() {
          const menu = document.getElementById("mobileMenu");
          const icon = document.getElementById("menuIcon");
          const isOpen = menu.classList.toggle("open");

          if (icon) {
              icon.setAttribute("data-lucide", isOpen ? "x" : "menu");
              initIcons();
          }

          // A11y
          const btn = document.getElementById("mobileMenuBtn");
          if (btn) btn.setAttribute("aria-expanded", String(isOpen));
      }

      // Navbar scroll behavior
      function handleNavbarOnScroll() {
          const navbar = document.getElementById("navbar");
          const logoText = document.getElementById("logo-text");
          const logoSubtext = document.getElementById("logo-subtext");
          const logoBox = document.getElementById("logo-box");

          if (!navbar) return;

          if (window.scrollY > 30) {
              navbar.classList.add("navbar-scrolled");
              navbar.classList.remove("py-8");
              navbar.classList.add("py-4");

              if (logoText) logoText.classList.add("text-white");
              if (logoSubtext) logoSubtext.classList.add("text-white/60");
              if (logoBox) logoBox.classList.add("shadow-md");
          } else {
              navbar.classList.remove("navbar-scrolled");
              navbar.classList.add("py-8");
              navbar.classList.remove("py-4");

              if (logoText) logoText.classList.remove("text-white");
              if (logoSubtext) logoSubtext.classList.remove("text-white/60");
              if (logoBox) logoBox.classList.remove("shadow-md");
          }
      }

      // Scroll reveal
      function initScrollReveal() {
          const revealEls = document.querySelectorAll(".scroll-reveal, .scroll-reveal-scale, .scroll-reveal-right, .scroll-reveal-left");

          const io = new IntersectionObserver((entries) => {
              entries.forEach((entry) => {
                  if (!entry.isIntersecting) return;
                  entry.target.classList.add("visible");
                  io.unobserve(entry.target);
              });
          }, { threshold: 0.12 });

          revealEls.forEach((el) => io.observe(el));
      }

